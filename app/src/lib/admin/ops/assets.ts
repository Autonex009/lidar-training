import fs from "node:fs";
import { z } from "zod";
import { db } from "@/lib/db";
import { safeResolve } from "@/lib/assets-store";
import { ADMIN_ONLY, defineOp, fail, okr } from "../types";

export const assetOps = {
  "asset.delete": defineOp({
    roles: ADMIN_ONLY,
    input: z.object({ id: z.string().min(1) }),
    async run(_a, i) {
      const asset = await db.pointCloudAsset.findUnique({ where: { id: i.id }, include: { _count: { select: { tasks: true } } } });
      if (!asset) return fail(404, "Asset not found.");
      if (asset._count.tasks > 0) return fail(409, `Asset is used by ${asset._count.tasks} task(s); reassign them first.`);
      await db.pointCloudAsset.delete({ where: { id: i.id } });
      // Uploaded assets own their directory; synthetic demo scenes are regenerated by the seed and kept on disk.
      if (!asset.isSynthetic) {
        const dir = safeResolve(asset.id);
        if (dir) fs.rmSync(dir, { recursive: true, force: true });
      }
      return okr({});
    },
  }),
};
